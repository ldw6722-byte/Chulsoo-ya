create table seller_applications (
    id bigint generated by default as identity primary key,
    applicant_user_id bigint not null unique references users(id),
    store_name varchar(100) not null,
    representative_name varchar(100) not null,
    business_registration_number varchar(20) not null,
    business_opened_on date,
    city_name varchar(60) not null,
    district_name varchar(60) not null,
    gu_code varchar(20) not null,
    address varchar(300) not null,
    phone varchar(255) not null,
    handled_items varchar(1000),
    status varchar(20) not null default 'PENDING',
    nts_status varchar(30) not null default 'NOT_REQUESTED',
    nts_message varchar(500),
    certificate_object_key varchar(500),
    certificate_content_type varchar(100),
    certificate_size_bytes bigint,
    submitted_at timestamptz not null default now(),
    reviewed_by_user_id bigint references users(id),
    reviewed_at timestamptz,
    rejection_reason varchar(500),
    version bigint,
    constraint ck_seller_application_status check (status in ('PENDING', 'MANUAL_REVIEW', 'APPROVED', 'REJECTED')),
    constraint ck_seller_application_nts_status check (nts_status in ('NOT_REQUESTED', 'VERIFIED', 'MISMATCH', 'UNAVAILABLE')),
    constraint ck_seller_application_certificate_size check (certificate_size_bytes is null or certificate_size_bytes between 102400 and 5242880)
);

create index ix_seller_applications_status_submitted on seller_applications(status, submitted_at);
